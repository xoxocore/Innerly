// Turns the reflection Jelly into the asset the check-in uses.
//
//   brand/jelly-reflect-source.png   Jelly holding a heart, on a white ground
//
// The same treatment as the logo: lifted off its white without leaving a halo,
// otherwise carried through exactly as drawn, with the eyes measured so that
// she blinks on this drawing the way she blinks on every other one. Nothing is
// cut out of her — she is not holding anything that moves.
//
// Writes:
//   public/innerly-reflect.png    the artwork, background removed
//   src/lib/reflect-jelly.ts      it as a data URI, the lid colour, the eyes
//
// Run with: node tools/prepare-reflect-jelly.mjs

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { decodePng, downscale, encodePng } from "./png.mjs";
import { CLOSE, GROW, crop, eyelidColour, findEyes, lift, opaqueBox } from "./jelly-lift.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "brand", "jelly-reflect-source.png");

/** Drawn at around 48px, so this stays crisp on the densest screen. */
const OUT = 256;

/** Room around her inside her square, as a share of her longest side. */
const PAD = 0.02;

const source = decodePng(await readFile(SOURCE));
const lifted = lift(source);

const bounds = opaqueBox(lifted);
const longest = Math.max(bounds.maxX - bounds.minX + 1, bounds.maxY - bounds.minY + 1);
const side = longest + Math.round(longest * PAD) * 2;
const cx = Math.round((bounds.minX + bounds.maxX) / 2);
const cy = Math.round((bounds.minY + bounds.maxY) / 2);
const half = Math.floor(side / 2);
const square = {
  minX: cx - half,
  minY: cy - half,
  maxX: cx - half + side - 1,
  maxY: cy - half + side - 1,
};

const cut = crop(lifted, square);
const png = encodePng(OUT, OUT, downscale(cut.rgba, cut.w, cut.h, OUT, OUT));
await writeFile(join(root, "public", "innerly-reflect.png"), png);

const [leftEye, rightEye] = findEyes(lifted);
const grow = Math.max(1, Math.round((leftEye.maxX - leftEye.minX + 1) * GROW));
const LID = eyelidColour(lifted, [leftEye, rightEye], grow);

const uri = (b) => `data:image/png;base64,${b.toString("base64")}`;
const pct = (n) => Number(n.toFixed(4));
const hex = (c) => "#" + c.map((v) => v.toString(16).padStart(2, "0")).join("");
const box = (e) => ({
  left: pct((e.minX - grow - square.minX) / side),
  top: pct((e.minY - grow - square.minY) / side),
  width: pct((e.maxX - e.minX + 1 + grow * 2) / side),
  height: pct((e.maxY - e.minY + 1 + grow * 2) / side),
});
const eyeHeight = leftEye.maxY - leftEye.minY + 1;

await writeFile(
  join(root, "src", "lib", "reflect-jelly.ts"),
  `// Generated by tools/prepare-reflect-jelly.mjs — do not edit by hand.
//
// Jelly holding a heart. Carried as a data URI so the single-file build has
// her too, and so she never arrives a frame after the page around her.

export const REFLECT_SRC =
  "${uri(png)}";

/** The skin colour a closed eyelid is painted in. */
export const REFLECT_EYELID = "${hex(LID)}";

/** How far down its box a lid comes when the eye is shut. */
export const REFLECT_SHUT = ${pct((CLOSE * eyeHeight + grow) / (eyeHeight + grow * 2))};

/**
 * The eyes, as a share of the square, measured from the drawing.
 *
 * A lid is drawn over these boxes and taken away again, so a blink cannot
 * damage a face it never touches.
 */
export const REFLECT_EYES = [
${[leftEye, rightEye]
  .map((e) => {
    const b = box(e);
    return `  { left: ${b.left}, top: ${b.top}, width: ${b.width}, height: ${b.height} },`;
  })
  .join("\n")}
];
`
);

const kb = (b) => (b.length / 1024).toFixed(1) + "KB";
console.log(`source     ${source.width}x${source.height} → ${side}x${side} → ${OUT}x${OUT}`);
console.log(`reflect    ${kb(png)}   lid ${hex(LID)}`);
console.log(`eyes       ${leftEye.maxX - leftEye.minX + 1}x${eyeHeight} and ${rightEye.maxX - rightEye.minX + 1}x${rightEye.maxY - rightEye.minY + 1}`);
